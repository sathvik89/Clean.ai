"""Turn a finished run into a reusable artifact.

The recipe is a standalone python script, built from the actions that
actually ran (including repairs), so next month's file can be cleaned
the same way without the app or an API key.
"""

from __future__ import annotations

import json
from datetime import datetime
from typing import Any, Dict, List

SCRIPT_HEADER = '''"""Cleaning recipe generated by Clean.ai on {date}.

Dataset: {dataset}
Goal: {goal}

Usage:
    python {script_name} input.csv output.csv
"""

import sys

import numpy as np
import pandas as pd

NULL_TOKENS = {{"n/a", "na", "null", "none", "nan", "-", "--", "?", "missing", "unknown", ""}}


def clean(df: pd.DataFrame) -> pd.DataFrame:
'''

SCRIPT_FOOTER = '''    return df


if __name__ == "__main__":
    source = sys.argv[1] if len(sys.argv) > 1 else "input.csv"
    target = sys.argv[2] if len(sys.argv) > 2 else "cleaned.csv"
    frame = pd.read_csv(source)
    cleaned = clean(frame)
    cleaned.to_csv(target, index=False)
    print(f"saved {len(cleaned)} rows to {target}")
'''


def _code_for_action(tool: str, args: Dict[str, Any]) -> List[str]:
    columns = args.get("columns")
    if tool == "normalize_nulls":
        target = f"{columns!r}" if columns else "df.columns"
        return [
            f"for col in {target}:",
            "    if df[col].dtype == object:",
            "        mask = df[col].notna() & df[col].astype(str).str.strip().str.lower().isin(NULL_TOKENS)",
            "        df.loc[mask, col] = pd.NA",
        ]
    if tool == "handle_missing":
        strategy = args.get("strategy", "median")
        lines = []
        target = columns if columns else None
        if strategy == "drop":
            return [f"df = df.dropna(subset={target!r})" if target else "df = df.dropna()"]
        loop_target = f"{target!r}" if target else "df.columns"
        if strategy in ("mean", "median"):
            lines += [
                f"for col in {loop_target}:",
                "    numeric = pd.to_numeric(df[col], errors='coerce')",
                f"    df[col] = numeric.fillna(numeric.{strategy}())",
            ]
        elif strategy == "constant":
            fill = args.get("fill_value", 0)
            lines += [f"df[{target!r}] = df[{target!r}].fillna({fill!r})" if target else f"df = df.fillna({fill!r})"]
        elif strategy == "interpolate":
            lines += [
                f"for col in {loop_target}:",
                "    numeric = pd.to_numeric(df[col], errors='coerce')",
                "    df[col] = df[col].fillna(numeric.interpolate(limit_direction='both'))",
            ]
        else:
            lines += [
                f"for col in {loop_target}:",
                "    modes = df[col].mode()",
                "    if not modes.empty:",
                "        df[col] = df[col].fillna(modes[0])",
            ]
        return lines
    if tool == "remove_duplicates":
        return [f"df = df.drop_duplicates(subset={columns!r})" if columns else "df = df.drop_duplicates()"]
    if tool == "convert_types":
        lines = []
        for col, target_type in (args.get("column_type_map") or {}).items():
            t = str(target_type).lower()
            if t in ("datetime", "date", "timestamp"):
                lines.append(f"df[{col!r}] = pd.to_datetime(df[{col!r}], errors='coerce', format='mixed')")
            elif t in ("int", "integer"):
                lines.append(f"df[{col!r}] = pd.to_numeric(df[{col!r}], errors='coerce').astype('Int64')")
            elif t in ("float", "number", "numeric"):
                lines.append(f"df[{col!r}] = pd.to_numeric(df[{col!r}], errors='coerce').astype(float)")
            else:
                lines.append(f"df[{col!r}] = df[{col!r}].astype({t!r})")
        return lines
    if tool == "clean_text":
        actions = set(args.get("actions") or [])
        lines = [f"for col in {columns!r}:", "    mask = df[col].notna()", "    s = df.loc[mask, col].astype(str)"]
        if "lowercase" in actions:
            lines.append("    s = s.str.lower()")
        if "uppercase" in actions:
            lines.append("    s = s.str.upper()")
        if "titlecase" in actions:
            lines.append("    s = s.str.title()")
        if "strip" in actions:
            lines.append("    s = s.str.strip()")
        if "collapse_spaces" in actions:
            lines.append("    s = s.str.replace(r'\\s+', ' ', regex=True)")
        if "remove_special" in actions:
            lines.append("    s = s.str.replace(r'[^\\w\\s@.\\-]', '', regex=True)")
        lines.append("    df.loc[mask, col] = s")
        return lines
    if tool == "fix_outliers":
        method = args.get("method", "clip")
        lines = [f"for col in {columns!r}:",
                 "    numeric = pd.to_numeric(df[col], errors='coerce')",
                 "    q1, q3 = numeric.quantile(0.25), numeric.quantile(0.75)",
                 "    low, high = q1 - 1.5 * (q3 - q1), q3 + 1.5 * (q3 - q1)"]
        if method == "nullify":
            lines.append("    df.loc[((numeric < low) | (numeric > high)).fillna(False), col] = pd.NA")
        else:
            lines.append("    df[col] = numeric.clip(lower=low, upper=high)")
        return lines
    if tool == "encode_categorical":
        if args.get("method") == "onehot":
            return [f"df = pd.get_dummies(df, columns={columns!r})"]
        return [f"for col in {columns!r}:", "    df[col] = df[col].astype('category').cat.codes"]
    if tool == "rename_columns":
        return [f"df = df.rename(columns={args.get('rename_map')!r})"]
    if tool == "drop_columns":
        return [f"df = df.drop(columns={columns!r})"]
    if tool == "run_pandas":
        code = args.get("code", "")
        return [line for line in code.splitlines()]
    return []


def build_recipe_script(summary: Dict[str, Any], script_name: str = "clean_recipe.py") -> str:
    header = SCRIPT_HEADER.format(
        date=datetime.now().strftime("%Y-%m-%d"),
        dataset=summary.get("dataset_name", "unknown"),
        goal=summary.get("user_context", "general cleaning"),
        script_name=script_name,
    )
    body_lines: List[str] = []
    applied = [r for r in summary.get("ledger", []) if r.get("status") == "ok" and r.get("delta")]
    if not applied:
        body_lines.append("    # no effective actions were recorded in this run")
    for record in applied:
        body_lines.append(f"    # action #{record['seq']}: {record['tool']} ({record.get('delta', '')[:70]})")
        for line in _code_for_action(record["tool"], record.get("args") or {}):
            body_lines.append(f"    {line}")
        body_lines.append("")
    return header + "\n".join(body_lines) + "\n" + SCRIPT_FOOTER


def build_plan_json(summary: Dict[str, Any]) -> str:
    payload = {
        "dataset": summary.get("dataset_name"),
        "goal": summary.get("user_context"),
        "generated": datetime.now().isoformat(timespec="seconds"),
        "steps": summary.get("steps", []),
        "actions": summary.get("ledger", []),
    }
    return json.dumps(payload, indent=2, default=str)
